def text(data, key, limit=10000, required=False):
    value = data.get(key, '')
    if not isinstance(value, str) or len(value) > limit or (required and not value.strip()):
        abort(400, description=f'{key.replace("_", " ")} must be {"nonempty " if required else ""}text of at most {limit} characters.')
    return value.strip()


def serialize_case(row):
    value = dict(row)
    for key in ('preconditions', 'test_steps', 'criterion_codes', 'introduced_values', 'assumption_reasons'):
        value[key] = json.loads(value.get(key) or '[]')
    value['stable_id'] = f"TC-{value['id']}"
    value['archived'] = bool(value['archived'])
    value['needs_confirmation'] = bool(value['needs_confirmation'])
    return value


def requirement_snapshot(c, rid):
    row = c.execute('SELECT id,project_id,content_revision,title,description,requirement_type,user_priority FROM requirements WHERE id=?', (rid,)).fetchone()
    value = dict(row)
    value['acceptance_criteria'] = [dict(v) for v in c.execute('SELECT criterion_code,description FROM requirement_acceptance_criteria WHERE requirement_id=? ORDER BY id', (rid,))]
    return value


def ensure_version(c, row, actor_id=None):
    existing = c.execute('SELECT id FROM test_case_versions WHERE scenario_id=? AND case_revision=?', (row['id'], row['case_revision'])).fetchone()
    if existing:
        return existing[0]
    source = requirement_snapshot(c, row['requirement_id'])
    if row['requirement_revision'] is not None and row['requirement_revision'] != source['content_revision']:
        previous = c.execute('SELECT snapshot FROM test_case_versions WHERE scenario_id=? AND requirement_revision=? ORDER BY case_revision DESC LIMIT 1',(row['id'],row['requirement_revision'])).fetchone()
        if previous is None:
            abort(409,description='Original requirement snapshot is unavailable; do not rewrite historical case evidence.')
        source = json.loads(previous['snapshot'])['requirement_snapshot']
    value = serialize_case(row)
    value['requirement_snapshot'] = source
    c.execute('INSERT INTO test_case_versions(scenario_id,case_revision,project_id,requirement_revision,actor_id,recorded_at,snapshot) VALUES(?,?,?,?,?,?,?) ON CONFLICT(scenario_id,case_revision) DO NOTHING',
              (row['id'],row['case_revision'],'current',row['requirement_revision'] or source['content_revision'],actor_id,_utc_timestamp(),json.dumps(value)))
    return c.execute('SELECT id FROM test_case_versions WHERE scenario_id=? AND case_revision=?', (row['id'],row['case_revision'])).fetchone()[0]


def register_generated_cases(c, rid, ids=None):
    req = c.execute('SELECT content_revision,user_priority,created_by_user_id FROM requirements WHERE id=?', (rid,)).fetchone()
    for row in c.execute('SELECT * FROM test_scenarios WHERE requirement_id=? AND archived=0', (rid,)).fetchall():
        if ids is not None and row['id'] not in ids:
            continue
        # Called only for newly generated rows, never for human-edited cases.
        c.execute("UPDATE test_scenarios SET requirement_revision=?,priority=?,review_status='Draft',created_by_user_id=?,clarification_notes=? WHERE id=?", (req['content_revision'],req['user_priority'],req['created_by_user_id'],explicit_clarification(c,rid,row),row['id']))
        ensure_version(c, c.execute('SELECT * FROM test_scenarios WHERE id=?',(row['id'],)).fetchone(), req['created_by_user_id'])


def archive_cases(c, rid):
    for row in c.execute('SELECT * FROM test_scenarios WHERE requirement_id=? AND archived=0',(rid,)).fetchall():
        ensure_version(c,row)
        c.execute('UPDATE test_scenarios SET archived=1,case_revision=case_revision+1 WHERE id=?',(row['id'],))
        ensure_version(c,c.execute('SELECT * FROM test_scenarios WHERE id=?',(row['id'],)).fetchone(),g.current_user['id'])


def validate_case(c, rid, data):
    if not isinstance(data, dict):
        abort(400, description='Send a test case object.')
    value = {key:text(data,key,limit,required) for key,limit,required in (
        ('title',200,True),('expected_result',10000,True),('test_data',10000,False),('clarification_notes',5000,False))}
    for key, allowed, default in (('category',('Positive','Negative','Boundary','Edge-case'),None),('test_type',CASE_TYPES,'Unspecified'),('priority',('Low','Medium','High'),'Medium')):
        item = data.get(key,default)
        if not isinstance(item,str) or item not in allowed:
            abort(400,description=f'Choose a valid {key}.')
        value[key] = item
    for key in ('preconditions','test_steps','criterion_codes'):
        items = data.get(key,[])
        if not isinstance(items,list) or len(items)>100 or any(not isinstance(v,str) or not v.strip() or len(v)>5000 for v in items) or (key=='test_steps' and not items):
            abort(400,description=f'{key} must be a bounded list of nonempty strings; execution steps are required.')
        value[key] = [v.strip() for v in items]
    valid = {r[0] for r in c.execute('SELECT criterion_code FROM requirement_acceptance_criteria WHERE requirement_id=?',(rid,))}
    if len(set(value['criterion_codes'])) != len(value['criterion_codes']) or any(v not in valid for v in value['criterion_codes']):
        abort(400,description='Link distinct acceptance criteria from this requirement only.')
    value['clarification_notes']=value['clarification_notes'] or explicit_clarification(c,rid,value)
    return value


def write_case(rid, sid, data, legacy=False):
    from app import get_connection
    from services.workflow_service import locked_requirement, snapshot
    from services.requirement_helpers import _get_requirement_detail
    c = get_connection()
    try:
        with c:
            if not isinstance(data,dict): abort(400)
            req = locked_requirement(c,rid,data)
            if req['created_by_user_id'] == g.current_user['id']:
                abort(403,description='Authors cannot review or prepare verification cases for their own requirement.')
            if legacy and req['review_status'] not in ('Ready for Review','In Review','Pending'):
                abort(409,description='Start a submitted review before revising scenarios.')
            row = None
            if sid is not None:
                row = c.execute('SELECT * FROM test_scenarios WHERE id=? AND requirement_id=?',(sid,rid)).fetchone()
                if row is None: abort(404)
                if row['archived']: abort(409,description='Archived cases are read-only. Create a new case for this version.')
                if not legacy and (type(data.get('case_revision')) is not int or data['case_revision'] != row['case_revision']):
                    abort(409,description='Case changed. Reload before editing.')
                data = {**serialize_case(row),**data}
            value = validate_case(c,rid,data)
            snapshot(c,rid,'before_test_case_edit')
            if row is not None:
                ensure_version(c,row)
                c.execute("UPDATE test_scenarios SET title=?,category=?,preconditions=?,test_data=?,test_steps=?,expected_result=?,test_type=?,priority=?,criterion_codes=?,clarification_notes=?,requirement_revision=?,case_revision=case_revision+1,review_status='Draft',review_notes='',source='original',needs_confirmation=1 WHERE id=?", (
                    value['title'],value['category'],json.dumps(value['preconditions']),value['test_data'],json.dumps(value['test_steps']),value['expected_result'],value['test_type'],value['priority'],json.dumps(value['criterion_codes']),value['clarification_notes'],req['content_revision'],sid))
            else:
                sql = "INSERT INTO test_scenarios(requirement_id,scenario_code,title,category,preconditions,test_data,test_steps,expected_result,test_type,priority,criterion_codes,clarification_notes,requirement_revision,created_by_user_id,source,needs_confirmation) VALUES(?,?,?,?,?,?,?,?,?,?,?,?,?,?,'original',1)"
                if c.dialect == 'postgres': sql += ' RETURNING id'
                cursor = c.execute(sql,(rid,'TC-'+uuid.uuid4().hex,value['title'],value['category'],json.dumps(value['preconditions']),value['test_data'],json.dumps(value['test_steps']),value['expected_result'],value['test_type'],value['priority'],json.dumps(value['criterion_codes']),value['clarification_notes'],req['content_revision'],g.current_user['id']))
                sid = cursor.fetchone()[0] if c.dialect == 'postgres' else cursor.lastrowid
            ensure_version(c,c.execute('SELECT * FROM test_scenarios WHERE id=?',(sid,)).fetchone(),g.current_user['id'])
            c.execute("UPDATE requirements SET revision=revision+1,updated_at=?,review_status=CASE WHEN review_status IN ('Ready for Review','Pending','Approved') THEN 'In Review' ELSE review_status END WHERE id=?",(_utc_timestamp(),rid))
            snapshot(c,rid,'test_case_saved')
            return {'requirement':_get_requirement_detail(c,rid),'test_case_id':sid}
    finally:
        c.close()


def review_case(rid,sid,data):
    from app import get_connection
    from services.workflow_service import locked_requirement, snapshot
    from services.requirement_helpers import _get_requirement_detail
    c = get_connection()
    try:
        with c:
            if not isinstance(data,dict): abort(400)
            req = locked_requirement(c,rid,data)
            if req['created_by_user_id'] == g.current_user['id']: abort(403)
            row = c.execute('SELECT * FROM test_scenarios WHERE id=? AND requirement_id=?',(sid,rid)).fetchone()
            if row is None: abort(404)
            if row['archived'] or type(data.get('case_revision')) is not int or data['case_revision'] != row['case_revision']:
                abort(409,description='Case changed or is archived. Reload before review.')
            target = data.get('review_status')
            allowed = {'Draft':('In Review',),'Needs Revision':('In Review',),'In Review':('Approved','Needs Revision','In Review')}
            if not isinstance(target,str) or target not in allowed.get(row['review_status'],()):
                abort(409,description='Start case review before deciding it. Edit an approved case to reopen its draft.')
            notes = text(data,'review_notes',5000,target=='Needs Revision')
            if target=='Approved' and (row['clarification_notes'] or explicit_clarification(c,rid,row) or row['requirement_revision'] != req['content_revision']):
                abort(409,description='Resolve clarification needs and rebase the case onto the current requirement before approval.')
            ensure_version(c,row)
            c.execute('UPDATE test_scenarios SET review_status=?,review_notes=?,needs_confirmation=?,case_revision=case_revision+1 WHERE id=?',(target,notes,int(target!='Approved'),sid))
            ensure_version(c,c.execute('SELECT * FROM test_scenarios WHERE id=?',(sid,)).fetchone(),g.current_user['id'])
            c.execute('UPDATE requirements SET revision=revision+1,updated_at=? WHERE id=?',(_utc_timestamp(),rid))
            snapshot(c,rid,'test_case_reviewed')
            return {'requirement':_get_requirement_detail(c,rid)}
    finally:
        c.close()


def record_execution(rid,sid,data):
    from app import get_connection
    from services.workflow_service import locked_requirement
    from admin_dashboard import record_activity
    if not isinstance(data,dict): abort(400)
    status = data.get('status')
    if not isinstance(status,str) or status not in EXECUTION_STATUSES: abort(400,description='Choose Not Run, Pass, Fail or Blocked.')
    value = {key:text(data,key,limit,required) for key,limit,required in (
        ('actual_result',20000,status in ('Pass','Fail')),('blocked_reason',5000,status=='Blocked'),
        ('environment',200,True),('build',200,True),('notes',10000,False),('evidence_reference',2000,False))}
    if any(key in data for key in ('tester_id','tester_name','executed_at','case_version_id','snapshot')):
        abort(400,description='Tester identity, time and case snapshot are recorded by the server.')
    request_key = request.headers.get('Idempotency-Key')
    if request_key is not None and not re.fullmatch(r'[A-Za-z0-9_-]{8,100}',request_key): abort(400)
    fingerprint = hashlib.sha256(json.dumps({'rid':rid,'sid':sid,'payload':data},sort_keys=True).encode()).hexdigest()
    c = get_connection()
    try:
        with c:
            # Lock once for a consistent source/case snapshot; execution itself
            # does not change requirement/case revisions or approval status.
            req = c.execute('SELECT revision FROM requirements WHERE id=?',(rid,)).fetchone()
            if req is None: abort(404)
            req = locked_requirement(c,rid,{'revision':req['revision']})
            if request_key:
                prior = c.execute('SELECT * FROM test_executions WHERE tester_id=? AND request_key=?',(g.current_user['id'],request_key)).fetchone()
                if prior:
                    if prior['input_hash'] != fingerprint: abort(409,description='This execution key belongs to a different submission.')
                    return {'execution':dict(prior)}
            row = c.execute('SELECT * FROM test_scenarios WHERE id=? AND requirement_id=?',(sid,rid)).fetchone()
            if row is None: abort(404)
            if row['archived'] or row['requirement_revision'] != req['content_revision']:
                abort(409,description='Case is archived or belongs to an earlier requirement version. Rebase a draft before executing.')
            if type(data.get('case_revision')) is not int or data['case_revision'] != row['case_revision']:
                abort(409,description='Case changed. Reload before recording execution.')
            if status in ('Pass','Fail') and (row['clarification_notes'] or explicit_clarification(c,rid,row)):
                abort(409,description='Expected behavior needs clarification. Record Blocked with a reason instead.')
            version_id = ensure_version(c,row)
            sql = 'INSERT INTO test_executions(scenario_id,case_version_id,project_id,requirement_revision,status,actual_result,blocked_reason,tester_id,tester_name,executed_at,environment,build,notes,evidence_reference,request_key,input_hash) VALUES(?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?) ON CONFLICT(tester_id,request_key) DO NOTHING'
            if c.dialect == 'postgres': sql += ' RETURNING id'
            cursor = c.execute(sql,(sid,version_id,'current',row['requirement_revision'],status,value['actual_result'],value['blocked_reason'],g.current_user['id'],g.current_user['name'],_utc_timestamp(),value['environment'],value['build'],value['notes'],value['evidence_reference'],request_key,fingerprint))
            if cursor.rowcount==0:
                prior=c.execute('SELECT * FROM test_executions WHERE tester_id=? AND request_key=?',(g.current_user['id'],request_key)).fetchone()
                if prior['input_hash'] != fingerprint:
                    abort(409,description='This execution key belongs to a different submission.')
                return {'execution':dict(prior)}
            eid = cursor.fetchone()[0] if c.dialect == 'postgres' else cursor.lastrowid
            record_activity(c,g.current_user,'manual_execution_recorded','test_execution',eid,f'Manual execution TC-{sid}: {status}')
            return {'execution':dict(c.execute('SELECT * FROM test_executions WHERE id=?',(eid,)).fetchone())}
    finally:
        c.close()


def read_cases(rid,sid=None,history=None):
    from app import get_connection
    c = get_connection()
    try:
        req = c.execute("SELECT id,content_revision FROM requirements WHERE id=? AND project_id='current'",(rid,)).fetchone()
        if req is None: abort(404)
        if sid is None:
            try:
                page=max(1,int(request.args.get('page','1')))
                size=min(100,max(1,int(request.args.get('page_size','50'))))
            except ValueError: abort(400)
            cases = []
            total = c.execute('SELECT COUNT(*) FROM test_scenarios WHERE requirement_id=?',(rid,)).fetchone()[0]
            for row in c.execute('SELECT s.*,(SELECT e.status FROM test_executions e JOIN test_case_versions v ON v.id=e.case_version_id WHERE e.scenario_id=s.id AND v.case_revision=s.case_revision ORDER BY e.id DESC LIMIT 1) AS latest_execution_status FROM test_scenarios s WHERE s.requirement_id=? ORDER BY s.archived,s.id LIMIT ? OFFSET ?',(rid,size,(page-1)*size)).fetchall():
                item = serialize_case(row)
                item['stale'] = row['requirement_revision'] != req['content_revision']
                item['latest_execution_status'] = item['latest_execution_status'] or 'Not Run'
                cases.append(item)
            return {'test_cases':cases,'content_revision':req['content_revision'],'page':page,'page_size':size,'total':total}
        if not c.execute('SELECT 1 FROM test_scenarios WHERE id=? AND requirement_id=?',(sid,rid)).fetchone(): abort(404)
        try:
            page=max(1,int(request.args.get('page','1')))
            size=min(100,max(1,int(request.args.get('page_size','20'))))
        except ValueError: abort(400)
        table = 'test_case_versions' if history=='versions' else 'test_executions'
        total = c.execute(f'SELECT COUNT(*) FROM {table} WHERE scenario_id=?',(sid,)).fetchone()[0]
        if history=='versions':
            rows = c.execute('SELECT * FROM test_case_versions WHERE scenario_id=? ORDER BY id DESC LIMIT ? OFFSET ?',(sid,size,(page-1)*size)).fetchall()
        else:
            rows = c.execute('SELECT e.*,v.snapshot FROM test_executions e JOIN test_case_versions v ON v.id=e.case_version_id WHERE e.scenario_id=? ORDER BY e.id DESC LIMIT ? OFFSET ?',(sid,size,(page-1)*size)).fetchall()
        items = [dict(row) for row in rows]
        for item in items: item['snapshot']=json.loads(item['snapshot'])
        return {history:items,'page':page,'page_size':size,'total':total}
    finally:
        c.close()
