"""Minimal V1 project: one persisted project, explicit context and existing access grant.

This deliberately rejects all other project identifiers; it is not multi-tenant hosting.
"""
from flask import abort, g


def initialize_project_schema(c):
    c.execute("CREATE TABLE IF NOT EXISTS projects (id TEXT PRIMARY KEY CHECK(id='current'), name TEXT NOT NULL, context TEXT NOT NULL DEFAULT '', revision INTEGER NOT NULL DEFAULT 1)")
    c.execute("INSERT INTO projects(id,name) VALUES('current','ReqQuality AI') ON CONFLICT(id) DO NOTHING")
    if c.dialect == 'postgres':
        c.execute("ALTER TABLE requirements ADD COLUMN IF NOT EXISTS project_id TEXT NOT NULL DEFAULT 'current' CHECK(project_id='current')")
    elif 'project_id' not in {r['name'] for r in c.execute('PRAGMA table_info(requirements)')}:
        c.execute("ALTER TABLE requirements ADD COLUMN project_id TEXT NOT NULL DEFAULT 'current' CHECK(project_id='current')")
    identity = 'BIGINT GENERATED BY DEFAULT AS IDENTITY' if c.dialect == 'postgres' else 'INTEGER'
    c.execute(f"CREATE TABLE IF NOT EXISTS requirement_analysis_drafts (id {identity} PRIMARY KEY, requirement_id BIGINT NOT NULL REFERENCES requirements(id) ON DELETE CASCADE, project_id TEXT NOT NULL REFERENCES projects(id), requirement_revision INTEGER NOT NULL, user_id BIGINT NOT NULL REFERENCES users(id), input_hash TEXT NOT NULL, result TEXT NOT NULL, created_at TEXT NOT NULL, UNIQUE(requirement_id,requirement_revision,user_id,input_hash))")
    c.commit()


def current_project(c):
    return dict(c.execute("SELECT id,name,context,revision FROM projects WHERE id='current'").fetchone())


def lock_project(c):
    # Serialize acceptance and context edits. Context cannot change between receipt
    # validation and persistence. SQLite BEGIN IMMEDIATE is already used by writes.
    if c.dialect == 'sqlite' and not c._connection.in_transaction:
        c.execute('BEGIN IMMEDIATE')
    return dict(c.execute("SELECT id,name,context,revision FROM projects WHERE id='current'" +
                          (' FOR UPDATE' if c.dialect == 'postgres' else '')).fetchone())


def update_context(c, data):
    if g.current_user['role'] != 'admin':
        abort(403)
    if not isinstance(data, dict) or not isinstance(data.get('context'), str) or len(data['context']) > 20000:
        abort(400, description='Project context must be text of at most 20,000 characters.')
    with c:
        project = lock_project(c)
        if type(data.get('revision')) is not int or data['revision'] != project['revision']:
            abort(409, description='Project context changed. Reload before saving.')
        if project['context'] != data['context'].strip():
            from admin_dashboard import record_activity
            c.execute("UPDATE projects SET context=?,revision=revision+1 WHERE id='current'", (data['context'].strip(),))
            record_activity(c, g.current_user, 'project_context_updated', 'project', None, 'Updated project context')
        return current_project(c)
