"""Failure-linked V1 bugs, explicit retests and append-only lifecycle history."""
import hashlib
import json
import re
from flask import abort, g, request

STATUSES = ('Open','In Progress','Ready for Retest','Closed')
FIELDS = ('title','preconditions','steps_to_reproduce','expected_result','actual_result','severity','priority','environment','build','evidence_reference')


def initialize_bug_schema(c):
    identity = 'BIGINT GENERATED BY DEFAULT AS IDENTITY' if c.dialect=='postgres' else 'INTEGER'
    c.execute(f"CREATE TABLE IF NOT EXISTS bugs (id {identity} PRIMARY KEY, project_id TEXT NOT NULL REFERENCES projects(id), requirement_id BIGINT NOT NULL REFERENCES requirements(id), scenario_id BIGINT NOT NULL REFERENCES test_scenarios(id), failed_execution_id BIGINT NOT NULL REFERENCES test_executions(id), title TEXT NOT NULL, preconditions TEXT NOT NULL, steps_to_reproduce TEXT NOT NULL, expected_result TEXT NOT NULL, actual_result TEXT NOT NULL, severity TEXT NOT NULL CHECK(severity IN ('Critical','High','Medium','Low')), priority TEXT NOT NULL CHECK(priority IN ('High','Medium','Low')), environment TEXT NOT NULL, build TEXT NOT NULL, evidence_reference TEXT NOT NULL DEFAULT '', status TEXT NOT NULL CHECK(status IN ('Open','In Progress','Ready for Retest','Closed')), reporter_id BIGINT NOT NULL REFERENCES users(id), reporter_name TEXT NOT NULL, created_at TEXT NOT NULL, updated_at TEXT NOT NULL, revision INTEGER NOT NULL DEFAULT 1, last_retest_execution_id BIGINT REFERENCES test_executions(id), resolution_reason TEXT NOT NULL DEFAULT '', request_key TEXT NOT NULL, input_hash TEXT NOT NULL, UNIQUE(reporter_id,request_key), UNIQUE(failed_execution_id,input_hash))")
    c.execute(f'CREATE TABLE IF NOT EXISTS bug_history (id {identity} PRIMARY KEY, bug_id BIGINT NOT NULL REFERENCES bugs(id), action TEXT NOT NULL, from_status TEXT, to_status TEXT NOT NULL, actor_id BIGINT NOT NULL REFERENCES users(id), actor_name TEXT NOT NULL, recorded_at TEXT NOT NULL, note TEXT NOT NULL, retest_execution_id BIGINT REFERENCES test_executions(id), snapshot TEXT NOT NULL)')
    c.execute('CREATE INDEX IF NOT EXISTS idx_bugs_failure ON bugs(failed_execution_id,id)')
    c.execute('CREATE INDEX IF NOT EXISTS idx_bug_history ON bug_history(bug_id,id)')
    c.commit()


def authorize_write(c):
    role=g.current_user['role']
    if role=='admin': return
    if role!='SQA Engineer': abort(403,description='Only authorized SQA Engineers and SQA Admins can manage bugs.')
    permission=c.execute("SELECT enabled FROM role_permissions WHERE role='SQA Engineer' AND permission='manage_bugs'").fetchone()
    if not permission or not permission['enabled']: abort(403,description='Bug management permission is required.')


def source_execution(c,eid):
    row=c.execute("SELECT e.*,s.requirement_id,v.snapshot FROM test_executions e JOIN test_scenarios s ON s.id=e.scenario_id JOIN requirements r ON r.id=s.requirement_id JOIN test_case_versions v ON v.id=e.case_version_id WHERE e.id=? AND e.project_id='current' AND s.project_id='current' AND r.project_id='current'",(eid,)).fetchone()
    if row is None: abort(404,description='Execution not found in this project.')
    return row


def public_bug(row):
    value=dict(row)
    for key in ('preconditions','steps_to_reproduce'): value[key]=json.loads(value[key])
    for key in ('request_key','input_hash'): value.pop(key,None)
    value['stable_id']=f"BUG-{value['id']}"
    return value


def prefill(execution):
    case=json.loads(execution['snapshot'])
    return dict(title=('Failure: '+case['title'])[:200],preconditions=case['preconditions'],steps_to_reproduce=case['test_steps'],expected_result=case['expected_result'],actual_result=execution['actual_result'],severity='Medium',priority=case['priority'] or 'Medium',environment=execution['environment'],build=execution['build'],evidence_reference=execution['evidence_reference'])


def validate(data):
    from services.case_service import text
    if not isinstance(data,dict): abort(400,description='Send a bug object.')
    value={key:text(data,key,limit,required) for key,limit,required in (
        ('title',200,True),('expected_result',20000,True),('actual_result',20000,True),('environment',200,True),('build',200,True),('evidence_reference',2000,False))}
    for key in ('preconditions','steps_to_reproduce'):
        items=data.get(key,[])
        if not isinstance(items,list) or len(items)>100 or any(not isinstance(v,str) or not v.strip() or len(v)>5000 for v in items) or (key=='steps_to_reproduce' and not items):
            abort(400,description=f'{key} must be a list of nonempty strings; reproduction steps are required.')
        value[key]=[v.strip() for v in items]
    for key,allowed in (('severity',('Critical','High','Medium','Low')),('priority',('High','Medium','Low'))):
        item=data.get(key)
        if not isinstance(item,str) or item not in allowed: abort(400,description=f'Choose a valid {key}.')
        value[key]=item
    if any(key not in (*FIELDS,'revision') for key in data):
        abort(400,description='Only editable bug fields are accepted. Links, status, reporter and timestamps are server-owned.')
    return value


def history(c,bid,action,previous=None,note='',retest=None):
    from services.requirement_helpers import _utc_timestamp
    from admin_dashboard import record_activity
    row=c.execute('SELECT * FROM bugs WHERE id=?',(bid,)).fetchone()
    c.execute('INSERT INTO bug_history(bug_id,action,from_status,to_status,actor_id,actor_name,recorded_at,note,retest_execution_id,snapshot) VALUES(?,?,?,?,?,?,?,?,?,?)',
              (bid,action,previous,row['status'],g.current_user['id'],g.current_user['name'],_utc_timestamp(),note,retest,json.dumps(public_bug(row))))
    record_activity(c,g.current_user,'bug_'+action,'bug',bid,f'BUG-{bid}: {row["status"]}')


def lock_bug(c,bid,data):
    if not isinstance(data,dict): abort(400)
    if c.dialect=='sqlite' and not c._connection.in_transaction: c.execute('BEGIN IMMEDIATE')
    row=c.execute("SELECT * FROM bugs WHERE id=? AND project_id='current'"+(' FOR UPDATE' if c.dialect=='postgres' else ''),(bid,)).fetchone()
    if row is None: abort(404)
    if type(data.get('revision')) is not int or data['revision']!=row['revision']:
        abort(409,description='Bug changed. Reload before saving.')
    return row


def create_bug(eid,data):
    from app import get_connection
    from services.requirement_helpers import _utc_timestamp
    c=get_connection()
    try:
        authorize_write(c)
        execution=source_execution(c,eid)
        if execution['status']!='Fail': abort(409,description='Create a bug from a failed manual execution only.')
        value=validate(data)
        fingerprint=hashlib.sha256(json.dumps(value,sort_keys=True).encode()).hexdigest()
        key=request.headers.get('Idempotency-Key') or 'body-'+fingerprint
        if not re.fullmatch(r'[A-Za-z0-9_-]{8,100}',key): abort(400,description='Invalid bug submission key.')
        with c:
            sql="INSERT INTO bugs(project_id,requirement_id,scenario_id,failed_execution_id,title,preconditions,steps_to_reproduce,expected_result,actual_result,severity,priority,environment,build,evidence_reference,status,reporter_id,reporter_name,created_at,updated_at,request_key,input_hash) VALUES('current',?,?,?,?,?,?,?,?,?,?,?,?,?,'Open',?,?,?,?,?,?) ON CONFLICT DO NOTHING"
            if c.dialect=='postgres': sql+=' RETURNING id'
            now=_utc_timestamp()
            cursor=c.execute(sql,(execution['requirement_id'],execution['scenario_id'],eid,value['title'],json.dumps(value['preconditions']),json.dumps(value['steps_to_reproduce']),value['expected_result'],value['actual_result'],value['severity'],value['priority'],value['environment'],value['build'],value['evidence_reference'],g.current_user['id'],g.current_user['name'],now,now,key,fingerprint))
            if cursor.rowcount==0:
                prior=c.execute('SELECT * FROM bugs WHERE reporter_id=? AND request_key=?',(g.current_user['id'],key)).fetchone()
                if prior and (prior['failed_execution_id']!=eid or prior['input_hash']!=fingerprint):
                    abort(409,description='This submission key belongs to different bug content.')
                prior=prior or c.execute('SELECT * FROM bugs WHERE failed_execution_id=? AND input_hash=?',(eid,fingerprint)).fetchone()
                return {'bug':public_bug(prior),'created':False},200
            bid=cursor.fetchone()[0] if c.dialect=='postgres' else cursor.lastrowid
            history(c,bid,'created')
            return {'bug':public_bug(c.execute('SELECT * FROM bugs WHERE id=?',(bid,)).fetchone()),'created':True},201
    finally: c.close()


def edit_bug(bid,data):
    from app import get_connection
    from services.requirement_helpers import _utc_timestamp
    c=get_connection()
    try:
        authorize_write(c)
        with c:
            row=lock_bug(c,bid,data)
            value=validate(data)
            c.execute('UPDATE bugs SET title=?,preconditions=?,steps_to_reproduce=?,expected_result=?,actual_result=?,severity=?,priority=?,environment=?,build=?,evidence_reference=?,revision=revision+1,updated_at=? WHERE id=?',
                      (value['title'],json.dumps(value['preconditions']),json.dumps(value['steps_to_reproduce']),value['expected_result'],value['actual_result'],value['severity'],value['priority'],value['environment'],value['build'],value['evidence_reference'],_utc_timestamp(),bid))
            history(c,bid,'edited',row['status'])
            return {'bug':public_bug(c.execute('SELECT * FROM bugs WHERE id=?',(bid,)).fetchone())}
    finally: c.close()


def transition(bid,data):
    from app import get_connection
    from services.requirement_helpers import _utc_timestamp
    from services.case_service import text
    c=get_connection()
    try:
        authorize_write(c)
        with c:
            row=lock_bug(c,bid,data)
            target=data.get('status')
            allowed={'Open':('In Progress',),'In Progress':('Ready for Retest',),'Ready for Retest':('Closed','Open'),'Closed':('Open',)}
            if not isinstance(target,str) or target not in allowed[row['status']]:
                abort(409,description='Use Open → In Progress → Ready for Retest → Closed, or reopen with a failed retest.')
            if any(key not in ('revision','status','note','retest_execution_id','resolution_reason') for key in data): abort(400)
            note=text(data,'note',5000)
            reason=text(data,'resolution_reason',5000)
            retest_id=data.get('retest_execution_id')
            retest=None
            if retest_id is not None:
                if type(retest_id) is not int: abort(400,description='Retest must be an execution ID.')
                retest=source_execution(c,retest_id)
                if retest['scenario_id']!=row['scenario_id'] or retest['requirement_id']!=row['requirement_id'] or retest_id<=row['failed_execution_id']:
                    abort(400,description='Link a later retest of this same project, requirement and test case.')
            if target=='Closed':
                if retest is not None:
                    latest_failure=c.execute("SELECT MAX(id) FROM test_executions WHERE scenario_id=? AND status='Fail'",(row['scenario_id'],)).fetchone()[0]
                    if retest['status']!='Pass' or retest_id<=latest_failure:
                        abort(409,description='Closure needs a passing retest after the latest failure, or omit the retest and document a resolution reason.')
                elif not reason:
                    abort(400,description='Closure requires a linked passing retest or a documented resolution reason.')
            elif target=='Open':
                if retest is None or retest['status']!='Fail' or retest_id<=(row['last_retest_execution_id'] or row['failed_execution_id']):
                    abort(409,description='Reopening requires a new linked failed retest.')
                reason=''
            elif retest is not None or reason:
                abort(400,description='Attach retest evidence and resolution only when closing or reopening.')
            linked=retest_id if retest is not None else None if target=='Closed' else row['last_retest_execution_id']
            c.execute('UPDATE bugs SET status=?,last_retest_execution_id=?,resolution_reason=?,revision=revision+1,updated_at=? WHERE id=?',(target,linked,reason if target in ('Closed','Open') else row['resolution_reason'],_utc_timestamp(),bid))
            history(c,bid,'status_changed',row['status'],note or reason,retest_id)
            return {'bug':public_bug(c.execute('SELECT * FROM bugs WHERE id=?',(bid,)).fetchone())}
    finally: c.close()


def read_bugs(eid=None,bid=None,events=False):
    from app import get_connection
    c=get_connection()
    try:
        if eid is not None:
            execution=source_execution(c,eid)
            rows=c.execute('SELECT * FROM bugs WHERE failed_execution_id=? ORDER BY id',(eid,)).fetchall()
            return {'bugs':[public_bug(v) for v in rows],'prefill':prefill(execution) if execution['status']=='Fail' else None}
        row=c.execute("SELECT * FROM bugs WHERE id=? AND project_id='current'",(bid,)).fetchone()
        if row is None: abort(404)
        if events:
            try: page=max(1,int(request.args.get('page','1')))
            except ValueError: abort(400)
            rows=c.execute('SELECT * FROM bug_history WHERE bug_id=? ORDER BY id DESC LIMIT 20 OFFSET ?',(bid,(page-1)*20)).fetchall()
            items=[dict(v) for v in rows]
            for item in items: item['snapshot']=json.loads(item['snapshot'])
            return {'history':items,'page':page,'page_size':20,'total':c.execute('SELECT COUNT(*) FROM bug_history WHERE bug_id=?',(bid,)).fetchone()[0]}
        retests=c.execute('SELECT id,status,executed_at,environment,build FROM test_executions WHERE scenario_id=? AND id>? ORDER BY id DESC LIMIT 50',(row['scenario_id'],row['failed_execution_id'])).fetchall()
        return {'bug':public_bug(row),'retests':[dict(v) for v in retests]}
    finally: c.close()
