def create_services(app, get_connection, roles_required, csrf_required, login_required):

    def get_roles(connection):
        return response_payload(permissions=list(PERMISSIONS), roles={role: {row['permission']: bool(row['enabled']) for row in connection.execute('SELECT permission,enabled FROM role_permissions WHERE role=?', (role,))} for role in DEFAULT_PERMISSIONS})

    def update_role(connection, role, payload):
        data = payload
        if role not in DEFAULT_PERMISSIONS or not isinstance(data, dict) or (not data) or any((key not in PERMISSIONS or type(value) is not bool for key, value in data.items())):
            raise DashboardError('Provide a supported role and boolean permissions.')
        for permission, enabled in data.items():
            connection.execute('UPDATE role_permissions SET enabled=? WHERE role=? AND permission=?', (int(enabled), role, permission))
        record_activity(connection, g.current_user, 'permissions_updated', 'role', None, f'Updated permissions for {role}')
        return response_payload(message='Role permissions saved.')

    def manager_dashboard(connection, query_params):
        return response_payload(build_dashboard(connection, parse_filters(query_params)))

    def manager_requirements(connection, query_params):
        filters = parse_filters(query_params)
        settings = connection.execute('SELECT overdue_days FROM organization_settings WHERE id=1').fetchone()
        rows = filter_requirements(load_requirements(connection, settings['overdue_days']), filters)
        start = (filters['page'] - 1) * filters['page_size']
        return response_payload(requirements=rows[start:start + filters['page_size']], total=len(rows), page=filters['page'], page_size=filters['page_size'])

    def assign_reviewer(connection, requirement_id, payload):
        data = payload
        if not isinstance(data, dict) or set(data) != {'reviewer_id'}:
            raise DashboardError('Choose a reviewer or Unassigned.')
        reviewer_id = data['reviewer_id']
        suffix = ' FOR UPDATE' if connection.dialect == 'postgres' else ''
        if reviewer_id is not None:
            if type(reviewer_id) is not int or reviewer_id < 1:
                raise DashboardError('Choose an active SQA Engineer.')
            reviewer = connection.execute('SELECT id,name,role,is_active FROM users WHERE id=?' + suffix, (reviewer_id,)).fetchone()
            if not reviewer or reviewer['role'] != 'SQA Engineer' or (not reviewer['is_active']):
                raise DashboardError('Choose an active SQA Engineer.')
        row = connection.execute('SELECT id,assigned_reviewer_user_id FROM requirements WHERE id=?' + suffix, (requirement_id,)).fetchone()
        if not row:
            raise DashboardError('Requirement not found.', 404)
        if row['assigned_reviewer_user_id'] != reviewer_id:
            connection.execute('UPDATE requirements SET assigned_reviewer_user_id=?,updated_at=? WHERE id=?', (reviewer_id, timestamp(), requirement_id))
            summary = f"Assigned REQ-{requirement_id} to {reviewer['name']}" if reviewer_id else f'Unassigned REQ-{requirement_id}'
            record_activity(connection, g.current_user, 'reviewer_assigned', 'requirement', requirement_id, summary)
        return response_payload(message='Reviewer assignment saved.')

    def manage_member(connection, user_id, payload):
        data = payload
        if not isinstance(data, dict) or not data or set(data) - {'role', 'is_active'}:
            raise DashboardError('Provide a supported role or active status.')
        suffix = ' FOR UPDATE' if connection.dialect == 'postgres' else ''
        member = connection.execute('SELECT id,name,role,is_active FROM users WHERE id=?' + suffix, (user_id,)).fetchone()
        if not member:
            raise DashboardError('Team member not found.', 404)
        if member['role'] == 'admin':
            raise DashboardError('QA Manager accounts cannot be changed from team management.', 403)
        if user_id == g.current_user['id']:
            raise DashboardError('You cannot change your own role or active status.', 403)
        role, active = (data.get('role', member['role']), data.get('is_active', bool(member['is_active'])))
        if role not in ('Manager', 'Analyst', 'SQA Engineer') or type(active) is not bool:
            raise DashboardError('Choose Manager, Analyst or SQA Engineer and a valid active status.')
        if role != member['role'] or active != bool(member['is_active']):
            connection.execute('UPDATE users SET role=?,is_active=?,auth_version=auth_version+1 WHERE id=?', (role, int(active), user_id))
            from services.token_service import revoke_user_tokens
            revoke_user_tokens(connection, user_id)
            if role != 'SQA Engineer' or not active:
                connection.execute("UPDATE requirements SET assigned_reviewer_user_id=NULL,updated_at=? WHERE assigned_reviewer_user_id=? AND review_status IN ('Pending','In Review','Needs Revision')", (timestamp(), user_id))
            record_activity(connection, g.current_user, 'member_updated', 'user', user_id, f"Updated {member['name']}: {role}, {('Active' if active else 'Disabled')}; open assignments cleared when ineligible")
        return response_payload(message='Team member updated. Existing sessions were invalidated.')

    def save_settings(connection, payload):
        data = payload
        if not isinstance(data, dict) or set(data) != {'name', 'overdue_days'}:
            raise DashboardError('Provide organization name and overdue review threshold.')
        name, days = (data['name'], data['overdue_days'])
        if not isinstance(name, str) or not 2 <= len(name.strip()) <= 100 or type(days) is not int or (not 1 <= days <= 90):
            raise DashboardError('Name must be 2-100 characters and overdue threshold 1-90 days.')
        connection.execute('UPDATE organization_settings SET name=?,overdue_days=? WHERE id=1', (name.strip(), days))
        record_activity(connection, g.current_user, 'settings_updated', 'organization', 1, 'Updated organization settings')
        return response_payload(message='Organization settings saved.')

    def change_password(connection, payload):
        data = payload
        if not isinstance(data, dict) or not isinstance(data.get('current_password'), str) or (not isinstance(data.get('new_password'), str)):
            raise DashboardError('Enter your current and new passwords.')
        if not 12 <= len(data['new_password']) <= 128 or len(data['current_password']) > 128:
            raise DashboardError('New password must be between 12 and 128 characters.')
        suffix = ' FOR UPDATE' if connection.dialect == 'postgres' else ''
        user = connection.execute('SELECT password_hash FROM users WHERE id=?' + suffix, (g.current_user['id'],)).fetchone()
        if not check_password_hash(user['password_hash'], data['current_password']):
            raise DashboardError('Current password is incorrect.', 400)
        connection.execute('UPDATE users SET password_hash=?,auth_version=auth_version+1 WHERE id=?', (generate_password_hash(data['new_password'], method='scrypt'), g.current_user['id']))
        from services.token_service import revoke_user_tokens
        revoke_user_tokens(connection, g.current_user['id'])
        g.clear_auth_cookies = True
        record_activity(connection, g.current_user, 'password_changed', 'user', g.current_user['id'], 'Changed account password')
        session.clear()
        return response_payload(message='Password changed. Sign in again on all devices.')
    return SimpleNamespace(get_roles=get_roles, update_role=update_role, manager_dashboard=manager_dashboard, manager_requirements=manager_requirements, assign_reviewer=assign_reviewer, manage_member=manage_member, save_settings=save_settings, change_password=change_password)
