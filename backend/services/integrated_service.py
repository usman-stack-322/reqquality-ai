DEFINITIONS = {
    'review_status': 'Pending includes authoring Draft/Ready for Review and approvals without a verified current reviewed version. Authoring state is retained separately.',
    'linked_requirements': 'Current requirements with at least one active current-content-version case explicitly linked to an existing acceptance criterion. A link does not prove complete test coverage.',
    'criterion_links': 'All current criteria have explicit links to current active cases. This measures recorded links, not semantic completeness or execution success.',
    'latest_execution': 'One latest execution per active current-content-version case, for its exact current case revision. No record means Not Run. Only Pass counts as passed; Blocked and Not Run never do.',
    'open_bugs': 'All non-Closed bugs in the project, including historical requirement versions, grouped by severity. Ready for Retest is still open.',
    'needs_review': 'Distinct current requirements with non-current approval, missing/stale analysis, missing/review-required criteria, uncovered/invalid criterion links, or missing/stale/unapproved/clarification-needed cases. Category counts can overlap.',
}


def initialize_integrated_schema(c):
    fields={'reviewed_content_revision':'INTEGER','criteria_review_required':'INTEGER NOT NULL DEFAULT 0'}
    existing=({r['name'] for r in c.execute('PRAGMA table_info(requirements)')} if c.dialect=='sqlite' else set())
    for name,definition in fields.items():
        if c.dialect=='postgres': c.execute(f'ALTER TABLE requirements ADD COLUMN IF NOT EXISTS {name} {definition}')
        elif name not in existing: c.execute(f'ALTER TABLE requirements ADD COLUMN {name} {definition}')
    identity='BIGINT GENERATED BY DEFAULT AS IDENTITY' if c.dialect=='postgres' else 'INTEGER'
    c.execute(f'CREATE TABLE IF NOT EXISTS requirement_versions (id {identity} PRIMARY KEY, requirement_id BIGINT NOT NULL REFERENCES requirements(id), project_id TEXT NOT NULL REFERENCES projects(id), content_revision INTEGER NOT NULL, actor_id BIGINT REFERENCES users(id), recorded_at TEXT NOT NULL, origin TEXT NOT NULL, snapshot TEXT NOT NULL, UNIQUE(requirement_id,content_revision))')
    c.execute(f'CREATE TABLE IF NOT EXISTS requirement_reviews (id {identity} PRIMARY KEY, requirement_id BIGINT NOT NULL REFERENCES requirements(id), project_id TEXT NOT NULL REFERENCES projects(id), content_revision INTEGER NOT NULL, status TEXT NOT NULL, reviewer_id BIGINT NOT NULL REFERENCES users(id), reviewer_name TEXT NOT NULL, notes TEXT NOT NULL, reviewed_at TEXT NOT NULL, snapshot TEXT NOT NULL)')
    c.execute('CREATE INDEX IF NOT EXISTS idx_requirement_reviews ON requirement_reviews(requirement_id,id)')
    # Recover only known content versions, never invent a reviewed version for legacy approval.
    for row in c.execute('SELECT requirement_id,actor_id,created_at,snapshot FROM requirement_history ORDER BY id').fetchall():
        try: value=json.loads(row['snapshot'])
        except (ValueError,TypeError): continue
        if isinstance(value,dict) and type(value.get('content_revision')) is int:
            remember_version(c,value,row['actor_id'],row['created_at'],'historical snapshot')
    for row in c.execute("SELECT * FROM requirements WHERE project_id='current'").fetchall():
        value=dict(row)
        value['acceptance_criteria']=[dict(v) for v in c.execute('SELECT * FROM requirement_acceptance_criteria WHERE requirement_id=?',(row['id'],))]
        remember_version(c,value,None,None,'first observed at migration; earlier history may be incomplete')
    c.commit()


def remember_version(c,record,actor=None,recorded_at=None,origin='saved version'):
    from services.requirement_helpers import _utc_timestamp
    value={key:record.get(key) for key in ('id','project_id','content_revision','title','description','requirement_type','user_priority','analysis_summary','acceptance_criteria')}
    c.execute('INSERT INTO requirement_versions(requirement_id,project_id,content_revision,actor_id,recorded_at,origin,snapshot) VALUES(?,?,?,?,?,?,?) ON CONFLICT(requirement_id,content_revision) DO NOTHING',
              (record['id'],record.get('project_id','current'),record['content_revision'],actor,recorded_at or _utc_timestamp(),origin,json.dumps(value)))


def review_status(row):
    status=row['review_status']
    if status=='Approved' and row.get('reviewed_content_revision')!=row['content_revision']: return 'Pending'
    return status if status in ('In Review','Approved','Needs Revision') else 'Pending'


def graph(c,rid):
    row=c.execute("SELECT * FROM requirements WHERE id=? AND project_id='current'",(rid,)).fetchone()
    if row is None: abort(404,description='Requirement not found in this project.')
    r=dict(row)
    versions=[dict(v) for v in c.execute('SELECT * FROM requirement_versions WHERE requirement_id=? ORDER BY content_revision DESC',(rid,))]
    for v in versions:
        v['snapshot']=json.loads(v['snapshot']);v['current']=v['content_revision']==r['content_revision']
    from services.case_service import serialize_case
    cases=[serialize_case(v) for v in c.execute('SELECT * FROM test_scenarios WHERE requirement_id=? ORDER BY id',(rid,))]
    case_versions=[dict(v) for v in c.execute('SELECT v.* FROM test_case_versions v JOIN test_scenarios s ON s.id=v.scenario_id WHERE s.requirement_id=? ORDER BY v.id',(rid,))]
    for v in case_versions: v['snapshot']=json.loads(v['snapshot'])
    executions=[dict(v) for v in c.execute('SELECT e.* FROM test_executions e JOIN test_scenarios s ON s.id=e.scenario_id WHERE s.requirement_id=? ORDER BY e.id',(rid,))]
    for e in executions:
        e.pop('request_key',None);e.pop('input_hash',None)
    from services.bug_service import public_bug
    bugs=[public_bug(v) for v in c.execute('SELECT * FROM bugs WHERE requirement_id=? ORDER BY id',(rid,))]
    bug_history=[dict(v) for v in c.execute('SELECT h.* FROM bug_history h JOIN bugs b ON b.id=h.bug_id WHERE b.requirement_id=? ORDER BY h.id',(rid,))]
    reviews=[dict(v) for v in c.execute('SELECT * FROM requirement_reviews WHERE requirement_id=? ORDER BY id',(rid,))]
    for v in reviews+bug_history: v['snapshot']=json.loads(v['snapshot'])
    return dict(project_id='current',requirement_id=rid,current_content_revision=r['content_revision'],sqa_review_status=review_status(r),authoring_status=r['review_status'],versions=versions,test_cases=cases,case_versions=case_versions,executions=executions,bugs=bugs,bug_history=bug_history,reviews=reviews,metric_definitions=DEFINITIONS)


def metric_source(c):
    """Request-local data only; never reused between requests or access checks."""
    from services.project_service import current_project
    from analyzers.llm_analyzer import generation_configuration
    return dict(context_revision=current_project(c)['revision'],config=generation_configuration(),
        requirements=[dict(v) for v in c.execute("SELECT id,title,content_revision,review_status,reviewed_content_revision,criteria_review_required,analysis_summary FROM requirements WHERE project_id='current'")],
        criteria=[dict(v) for v in c.execute('SELECT requirement_id,criterion_code FROM requirement_acceptance_criteria')],
        cases=[dict(v) for v in c.execute('SELECT s.id,s.requirement_id,s.requirement_revision,s.review_status,s.clarification_notes,s.criterion_codes, (SELECT e.status FROM test_executions e JOIN test_case_versions v ON v.id=e.case_version_id WHERE e.scenario_id=s.id AND v.case_revision=s.case_revision ORDER BY e.id DESC LIMIT 1) AS latest_status FROM test_scenarios s WHERE s.archived=0')],
        bugs=[dict(v) for v in c.execute("SELECT requirement_id,severity FROM bugs WHERE project_id='current' AND status!='Closed'")])


def metrics(c, requirement_ids=None, source=None):
    source=source if source is not None else metric_source(c)
    context_revision=source['context_revision'];config=source['config']
    requirements=source['requirements']
    if requirement_ids is not None: requirements=[r for r in requirements if r['id'] in requirement_ids]
    ids={r['id'] for r in requirements}
    criteria={rid:set() for rid in ids}
    for a in source['criteria']:
        if a['requirement_id'] in ids: criteria[a['requirement_id']].add(a['criterion_code'])
    cases={rid:[] for rid in ids}
    for v in source['cases']:
        if v['requirement_id'] in ids: cases[v['requirement_id']].append(dict(v))
    statuses={k:0 for k in ('Pending','In Review','Approved','Needs Revision')}
    latest={k:0 for k in ('Not Run','Pass','Fail','Blocked')}
    severity={k:0 for k in ('Critical','High','Medium','Low')}
    linked_count=complete_links=case_count=0
    needing=[];states={}
    for r in requirements:
        rid=r['id']; codes=criteria[rid]; all_cases=cases[rid]
        current=[v for v in all_cases if v['requirement_revision']==r['content_revision']]
        links=set()
        for case in current:
            links.update(json.loads(case['criterion_codes'] or '[]'))
            latest[case['latest_status'] or 'Not Run']+=1
        linked=bool(links & codes); complete=bool(codes) and codes.issubset(links) and not (links-codes)
        linked_count+=int(linked);complete_links+=int(complete);case_count+=len(current)
        status=review_status(r);statuses[status]+=1
        try: analysis=json.loads(r['analysis_summary'] or '{}')
        except (ValueError,TypeError): analysis={}
        if not isinstance(analysis,dict): analysis={}
        reasons=[]
        if status!='Approved': reasons.append('Requirement review')
        saved_input=analysis.get('analysis_input') or {}
        if analysis.get('analysis_mode')!='ai_only' or analysis.get('stale') or saved_input.get('context_revision')!=context_revision or saved_input.get('generation_config')!=config: reasons.append('Analysis missing or stale')
        if not codes or r['criteria_review_required']: reasons.append('Acceptance criteria')
        if not complete: reasons.append('Criterion links')
        if not current or any(v['review_status']!='Approved' or v['clarification_notes'] for v in current) or len(current)!=len(all_cases): reasons.append('Test cases')
        if reasons: needing.append(dict(id=rid,title=r['title'],content_revision=r['content_revision'],reasons=reasons))
        states[rid]=dict(linked=linked,all_criteria_linked=complete,current_case_count=len(current),sqa_review_status=status,needs_review=bool(reasons))
    for bug in source['bugs']:
        if bug['requirement_id'] in ids: severity[bug['severity']]+=1
    return dict(review_status_counts=statuses,requirements_with_linked_cases=linked_count,requirements_without_linked_cases=len(ids)-linked_count,requirements_with_all_criteria_linked=complete_links,current_test_case_count=case_count,latest_execution_counts=latest,open_bugs_by_severity=severity,items_needing_review_count=len(needing),items_needing_review=needing[:20],metric_definitions=DEFINITIONS,requirement_states=states)
